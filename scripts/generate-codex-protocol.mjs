#!/usr/bin/env node

import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtemp, mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDir = path.join(root, 'packages/web/server/lib/codex/generated');
const evidencePath = path.join(root, 'docs/.codex-app-server-spike/report.json');
const expectedCodexVersion = 'codex-cli 0.147.0';
const sourceFiles = [
  'JSONRPCMessage.json',
  'ClientRequest.json',
  'ServerRequest.json',
  'ServerNotification.json',
];

const sha256 = (value) => createHash('sha256').update(value).digest('hex');
const json = (value) => `${JSON.stringify(value, null, 2)}\n`;
const nestedJson = (value) => JSON.stringify(value, null, 2).replaceAll('\n', '\n  ');

const run = (command, args) => {
  const result = spawnSync(command, args, {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
  if (result.status !== 0) {
    throw new Error(`${command} failed with exit ${result.status ?? 'unknown'}`);
  }
  return result.stdout.trim();
};

const readJson = async (file) => JSON.parse(await readFile(file, 'utf8'));

const hashDirectory = async (directory) => {
  const files = [];
  const visit = async (current) => {
    for (const entry of await readdir(current, { withFileTypes: true })) {
      const target = path.join(current, entry.name);
      if (entry.isDirectory()) await visit(target);
      else files.push(target);
    }
  };
  await visit(directory);
  files.sort();
  const digest = createHash('sha256');
  for (const file of files) {
    digest.update(path.relative(directory, file)).update('\0').update(await readFile(file)).update('\0');
  }
  return digest.digest('hex');
};

const extractMethods = (schema, name) => {
  if (!Array.isArray(schema.oneOf)) throw new Error(`${name} schema has no oneOf method union`);
  const methods = schema.oneOf.map((entry) => entry?.properties?.method?.enum?.[0]);
  if (methods.some((method) => typeof method !== 'string')) {
    throw new Error(`${name} schema contains an invalid method branch`);
  }
  return [...new Set(methods)].sort();
};

const renderDescriptor = ({ aggregateHash, clientRequests, serverRequests, serverNotifications }) => `// Generated by scripts/generate-codex-protocol.mjs from ${expectedCodexVersion}.
// Do not edit manually. Regenerate and review protocol drift instead.

export const CODEX_PROTOCOL = Object.freeze({
  codexVersion: '${expectedCodexVersion}',
  experimental: true,
  sourceAggregateSha256: '${aggregateHash}',
  clientRequests: Object.freeze(${nestedJson(clientRequests)}),
  serverRequests: Object.freeze(${nestedJson(serverRequests)}),
  serverNotifications: Object.freeze(${nestedJson(serverNotifications)}),
});

export class CodexProtocolError extends Error {
  constructor(code, message) {
    super(message);
    this.name = 'CodexProtocolError';
    this.code = code;
  }
}

const hasOwn = (value, key) => Object.prototype.hasOwnProperty.call(value, key);
const isRequestId = (value) => typeof value === 'string' || Number.isInteger(value);

const invalid = (reason) => {
  throw new CodexProtocolError('invalid-protocol-message', \`Invalid Codex protocol message: \${reason}\`);
};

export const parseCodexProtocolMessage = (value) => {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) {
    return invalid('expected an object');
  }

  const hasId = hasOwn(value, 'id');
  const hasMethod = hasOwn(value, 'method');
  const hasResult = hasOwn(value, 'result');
  const hasError = hasOwn(value, 'error');

  if (hasId && !isRequestId(value.id)) invalid('id must be a string or integer');

  if (hasMethod) {
    if (typeof value.method !== 'string') invalid('method must be a string');
    if (hasResult || hasError) invalid('method frames cannot contain response fields');
    return value;
  }

  if (!hasId) invalid('response is missing id');
  if (hasResult === hasError) invalid('response must contain exactly one of result or error');
  if (hasError) {
    const error = value.error;
    if (error === null || typeof error !== 'object' || Array.isArray(error)) {
      invalid('error must be an object');
    }
    if (!Number.isInteger(error.code) || typeof error.message !== 'string') {
      invalid('error must contain integer code and string message');
    }
  }
  return value;
};
`;

const buildOutputs = async (schemaDir, evidence) => {
  const selected = Object.fromEntries(await Promise.all(sourceFiles.map(async (name) => {
    const bytes = await readFile(path.join(schemaDir, name));
    return [name, { bytes, schema: JSON.parse(bytes.toString('utf8')), sha256: sha256(bytes) }];
  })));
  const clientRequests = extractMethods(selected['ClientRequest.json'].schema, 'ClientRequest');
  const serverRequests = extractMethods(selected['ServerRequest.json'].schema, 'ServerRequest');
  const serverNotifications = extractMethods(selected['ServerNotification.json'].schema, 'ServerNotification');
  const protocolSchema = json(selected['JSONRPCMessage.json'].schema);
  const protocolDescriptor = renderDescriptor({
    aggregateHash: evidence.schemas.json.sha256,
    clientRequests,
    serverRequests,
    serverNotifications,
  });
  const manifest = json({
    schemaVersion: 1,
    codexVersion: expectedCodexVersion,
    experimental: true,
    sourceAggregateSha256: evidence.schemas.json.sha256,
    sourceFiles: Object.fromEntries(sourceFiles.map((name) => [name, selected[name].sha256])),
    methodCounts: {
      clientRequests: clientRequests.length,
      serverRequests: serverRequests.length,
      serverNotifications: serverNotifications.length,
    },
    outputs: {
      'protocol-descriptor.js': sha256(protocolDescriptor),
      'protocol.schema.json': sha256(protocolSchema),
    },
  });
  return {
    'protocol-descriptor.js': protocolDescriptor,
    'protocol.schema.json': protocolSchema,
    'manifest.json': manifest,
  };
};

const main = async () => {
  const check = process.argv.includes('--check');
  const evidence = await readJson(evidencePath);
  const codexVersion = run('codex', ['--version']);
  if (codexVersion !== expectedCodexVersion || evidence.versions.codex !== expectedCodexVersion) {
    throw new Error(`Codex version mismatch; expected ${expectedCodexVersion}`);
  }

  const schemaDir = await mkdtemp(path.join(os.tmpdir(), 'openchamber-codex-schema-'));
  try {
    run('codex', ['app-server', 'generate-json-schema', '--experimental', '--out', schemaDir]);
    const aggregateHash = await hashDirectory(schemaDir);
    if (aggregateHash !== evidence.schemas.json.sha256) {
      throw new Error('Generated Codex schema does not match the WU0 aggregate hash');
    }
    const outputs = await buildOutputs(schemaDir, evidence);
    if (check) {
      for (const [name, expected] of Object.entries(outputs)) {
        const actual = await readFile(path.join(outputDir, name), 'utf8').catch(() => null);
        if (actual !== expected) throw new Error(`${name} is not deterministic or is out of date`);
      }
      console.log('Codex protocol generation check: PASS');
      return;
    }
    await mkdir(outputDir, { recursive: true });
    await Promise.all(Object.entries(outputs).map(([name, content]) => (
      writeFile(path.join(outputDir, name), content)
    )));
    console.log('Generated Codex protocol contract for codex-cli 0.147.0');
  } finally {
    await rm(schemaDir, { recursive: true, force: true });
  }
};

main().catch((error) => {
  console.error(`Codex protocol generation failed: ${error.message}`);
  process.exitCode = 1;
});
